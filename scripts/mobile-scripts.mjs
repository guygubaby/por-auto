import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { mkdir, readFile, readdir, lstat, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Script } from 'node:vm';

const require = createRequire(import.meta.url);
const core = require('../mobile/autojs6/updater-core.cjs');
const root = fileURLToPath(new URL('../', import.meta.url));
const json = value => `${JSON.stringify(value, null, 2)}\n`;
const sha = bytes => createHash('sha256').update(bytes).digest('hex');

async function sourceFiles(directory, prefix = '') {
  const files = [];
  for (const item of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
    const path = `${prefix}${item.name}`;
    core.relative(path);
    assert.ok(!item.isSymbolicLink(), `Symlink not allowed: ${path}`);
    if (item.isDirectory()) files.push(...await sourceFiles(resolve(directory, item.name), `${path}/`));
    else {
      assert.ok(item.isFile(), `Only regular files are allowed: ${path}`);
      const bytes = await readFile(resolve(directory, item.name));
      assert.ok(bytes.length <= core.limits.file, `File too large: ${path}`);
      if (path.endsWith('.js')) new Script(bytes.toString('utf8'), { filename: path });
      files.push({ path, size: bytes.length, sha256: sha(bytes), bytes });
    }
  }
  return files;
}

export async function buildMobileCatalog(directory = resolve(root, 'mobile-workflows')) {
  const workflows = [];
  const bundleFiles = [];
  let total = 0;
  for (const folder of (await readdir(directory, { withFileTypes: true })).sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0)) {
    assert.ok(!folder.isSymbolicLink(), `Symlink not allowed: ${folder.name}`);
    if (!folder.isDirectory()) continue;
    const metadata = JSON.parse(await readFile(resolve(directory, folder.name, 'workflow.json'), 'utf8'));
    assert.equal(metadata.schemaVersion, 1);
    assert.equal(metadata.id, folder.name);
    const source = resolve(directory, folder.name, 'src');
    assert.ok((await lstat(source)).isDirectory(), 'src must be a regular directory');
    const files = await sourceFiles(source);
    workflows.push({ ...metadata, files: files.map(({ bytes, ...file }) => file) });
    for (const file of files) {
      total += file.size;
      bundleFiles.push({ id: metadata.id, path: file.path, base64: file.bytes.toString('base64') });
    }
  }
  assert.ok(total <= core.limits.package, 'Offline package must not exceed 10 MiB');
  const catalog = core.catalog({ schemaVersion: 1, name: 'Por Auto 手机脚本', workflows });
  return { catalog, bundle: { schemaVersion: 1, catalog, files: bundleFiles } };
}

export async function buildBootstrap(bundle) {
  const [coreCode, runtime, launcher] = await Promise.all([
    readFile(resolve(root, 'mobile/autojs6/updater-core.cjs'), 'utf8'),
    readFile(resolve(root, 'mobile/autojs6/runtime-autojs6.js'), 'utf8'),
    readFile(resolve(root, 'mobile/autojs6/launcher-main.js'), 'utf8'),
  ]);
  const demo = bundle.catalog.workflows.filter(p => p.id === 'demo-hello');
  assert.equal(demo.length, 1, 'The offline bootstrap requires the harmless demo-hello example');
  const bundled = { schemaVersion: 1, catalog: { schemaVersion: 1, name: '离线测试脚本', workflows: demo }, files: bundle.files.filter(f => f.id === 'demo-hello') };
  const text = `// GENERATED by pnpm mobile:bundle. Import this file in official AutoJs6 6.7.0+.\n// Launcher protocol ${core.launcherVersion}; scripts update independently from GitHub.\n(function () {\n'use strict';\nvar core = (function () { var module = { exports: {} };\n${coreCode}\nreturn module.exports; })();\n${runtime}\n${launcher}\ntry { launchMobileScripts(core, createAutoJs6Runtime(), ${JSON.stringify(bundled)}); }\ncatch (error) { dialogs.alert('启动器未能运行', String(error.message || error)); }\n})();\n`;
  new Script(text, { filename: 'bootstrap.js' });
  return text;
}

export async function mobileWechatDefinitions() {
  const names = ['wechat-open', 'wechat-nickname', 'wechat-first-chat', 'wechat-send-hello', 'wechat-broadcast'];
  const workflows = await Promise.all(names.map(async name => JSON.parse(await readFile(resolve(root, 'workflows', name, 'workflow.json'), 'utf8'))));
  const visual = await readFile(resolve(root, 'src-tauri/src/visual.rs'), 'utf8');
  const protocol = visual.match(/const PROTOCOL: &str = r#"([\s\S]*?)"#;/)?.[1];
  assert.ok(protocol, 'The phone runner requires the same page observation contract as desktop');
  return '// GENERATED by pnpm mobile:bundle from the desktop workflow definitions.\nmodule.exports = ' + JSON.stringify({ schemaVersion: 1, workflows, protocol }, null, 2) + ';\n';
}

export function assertVersionProgress(previous, current) {
  for (const next of current.workflows) {
    const old = previous.workflows.find(p => p.id === next.id);
    if (!old) continue;
    assert.ok(next.versionCode >= old.versionCode, `${next.id}: versionCode cannot decrease`);
    const identity = p => JSON.stringify({ version: p.version, entry: p.entry, minLauncher: p.minLauncher, minAutoJs6: p.minAutoJs6, files: p.files });
    if (identity(old) !== identity(next)) assert.ok(next.versionCode > old.versionCode, `${next.id}: script content changed; increment versionCode before publishing`);
  }
}

async function main() {
  const command = process.argv[2] || 'check';
  assert.ok(['check', 'bundle'].includes(command), 'Use check or bundle');
  const definitions = await mobileWechatDefinitions();
  const definitionsPath = resolve(root, 'mobile-workflows/wechat-suite/src/definitions.js');
  if (command === 'bundle') await writeFile(definitionsPath, definitions);
  else assert.equal(await readFile(definitionsPath, 'utf8'), definitions, 'Phone workflow definitions are stale; run pnpm mobile:bundle');
  const { catalog, bundle } = await buildMobileCatalog();
  try {
    const previous = core.catalog(JSON.parse(await readFile(resolve(root, 'mobile-workflows/registry.json'), 'utf8')));
    assertVersionProgress(previous, catalog);
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const bootstrap = await buildBootstrap(bundle);
  const outputs = new Map([
    ['mobile-workflows/registry.json', json(catalog)],
    ['mobile-workflows/offline-bundle.json', json(bundle)],
    ['mobile/autojs6/bootstrap.js', bootstrap],
  ]);
  for (const [path, contents] of outputs) {
    if (command === 'check') assert.equal(await readFile(resolve(root, path), 'utf8'), contents, `${path} is stale; run pnpm mobile:bundle`);
    else await writeFile(resolve(root, path), contents);
  }
  if (command === 'bundle') {
    await mkdir(resolve(root, 'deliverables'), { recursive: true });
    await writeFile(resolve(root, 'deliverables/PorAuto-AutoJs6-bootstrap.js'), bootstrap);
    await writeFile(resolve(root, 'deliverables/PorAuto-mobile-scripts.json'), json(bundle));
  }
  console.log(`Mobile ${command}: ${catalog.workflows.length} package(s), launcher ${(Buffer.byteLength(bootstrap) / 1024).toFixed(1)} KiB; hashes and syntax verified`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error.message); process.exitCode = 1; });
}
